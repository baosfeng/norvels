/** 懒建查表：模块加载时不建 Map，读者没开转换就一分钱不花。 */
let dict: Map<string, string> | null = null;

function table(): Map<string, string> {
  if (!dict) {
    const map = new Map<string, string>();
    for (let i = 0; i < TRAD.length; i += 1) map.set(TRAD[i], SIMP[i]);
    dict = map;
  }
  return dict;
}

/** 表里有多少条对照（测试与调试用）。 */
export function trad2simpEntries(): number {
  return table().size;
}

/**
 * 把正文里的繁体字换成简体字。表里没有的字（简体字、标点、拉丁字母、数字、
 * 表情符号）原样保留；纯简体正文走「零替换」快路径，直接返回入参，不新建字符串。
 */
export function tradToSimp(text: string): string {
  if (text.length === 0) return text;
  const map = table();
  let out = "";
  let from = 0;
  for (let i = 0; i < text.length; i += 1) {
    const simp = map.get(text[i]);
    if (simp === undefined) continue;
    if (from < i) out += text.slice(from, i);
    out += simp;
    from = i + 1;
  }
  // from === 0 表示一次都没替换：纯简体正文直接返回原串
  return from === 0 ? text : out + text.slice(from);
}
