-- 0013 同书卷名唯一索引（表达式索引，TRIM(title)）。
--
-- 目的：把「同书卷名唯一」从「事务内查重」升级成数据库约束。查重与插入之间没有锁，
-- 多进程同时建同名卷时两者都会通过查重；唯一索引是这条竞态的兜底（写错误被翻译成
-- 既有哨兵 ErrVolumeNameTaken，api 仍映射 409）。
--
-- 两件事都在同一个事务里，由 Go 步骤 dedupeVolumeTitlesStep（migrate_steps.go）完成：
--   1. 老库里同书 TRIM(title) 重复的卷改名去重：按 (idx, id) 保留首个，
--      其余改成「原标题 (2)」「原标题 (3)」…（序号跳过本书已被占用的名字）；
--   2. 建 uq_volumes_book_title(book_id, TRIM(title))。
-- 改名条数打在迁移日志里，便于事后核对「这台机器上到底改了几条」。
--
-- 为什么去重不写成 SQL：补序号要先知道本书已有哪些卷名，才能保证新名字不会又撞上
-- 真实存在的「原标题 (2)」；纯 SQL 没有有界探测，改名撞唯一约束会让整条迁移回滚、
-- 服务起不来。SQLite 支持表达式唯一索引，索引与查重用的是同一个 TRIM 口径。
--
-- 只加索引、改标题，不动正文块与章节，不需要 VACUUM。
--
-- SQL 阶段没有自己的语句：保留一句无副作用的 SELECT，让「迁移 SQL 非空」的既有约束继续成立。

