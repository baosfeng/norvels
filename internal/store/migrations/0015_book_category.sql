-- 0015 书籍分类：大分类（category_l1）+ 小分类（category_l2），对齐网盘按起点规范整理的两级目录。
--
-- 结构变更全部在 Go 步骤 addCategoryColumnsStep 里完成，顺序是：加列 → 建索引 → 存量回填。
-- 原因：SQLite 的 ADD COLUMN 没有 IF NOT EXISTS（版本回退重跑会撞 duplicate column），
-- 而索引又依赖新列，所以两者都必须在同一事务的步骤里按序执行（与 0008/0010/0011/0014 同一条路径）。
--
-- 存量回填：加列的那一刻，库里已有的书统一记为部署方指定的回填分类
-- （环境变量 NORVELS_LEGACY_CATEGORY，缺省「未分类」）——它们没有来源目录可推断。
-- 回填只在「首次加列」时执行一次，迁移重放不会再覆盖后来按目录导入的书。
--
-- 导入侧口径：文件的相对导入根路径前两级目录即 (l1, l2)，数字前缀（01玄幻→玄幻）剥掉，
-- 下划线开头的目录（_待删除_*）不参与分类。

